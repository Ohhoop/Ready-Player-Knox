function a.wrap(b)
b=b%d
if b<0 then
b=b+d
end
return b
end

local m=a.wrap

function a.wrapFine(b)
b=b%a.FINE_TURN
if b<0 then
b=b+a.FINE_TURN
end
return b
end

function a.sin(b)
b=m(b)
if b<=c then
return h[b+1]
elseif b<=2*c then
return h[2*c-b+1]
elseif b<=3*c then
return-h[b-2*c+1]
end
return-h[d-b+1]
end

function a.cos(b)
return a.sin(b+c)
end

function a.divide(b,f)
if b>=0 then
return e(b/f)
end
return-e(-b/f)
end

function a.delta(f,g)
local b=m(g-f)
if b>=d/2 then
b=b-d
end
return b
end

function a.deltaFine(f,g)
local b=a.wrapFine(g-f)
if b>=a.FINE_TURN/2 then
b=b-a.FINE_TURN
end
return b
end

function a.atan2(f,g)
if g==0 and f==0 then
return 0
end
local j,k=g<0 and-g or g,f<0 and-f or f
local b
if j>=k then
b=l[e(k*256/j)+1]
else
b=c*i-l[e(j*256/k)+1]
end
if g<0 then
b=2*c*i-b
end
if f<0 then
b=d*i-b
end
return a.wrapFine(b)
end

function a.length(b,f)
return e(math.sqrt(b*b+f*f))
end
